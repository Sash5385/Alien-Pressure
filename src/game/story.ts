/** Сюжет кампанії: 15 місій, боси на 5-й і 10-й, фінал — 15-та. */
export const FINAL_MISSION = 15;

const ACTS: { from: number; title: string; text: string }[] = [
  { from: 1, title: 'Розділ 1 · Перший контакт', text: 'Над околицями впали кораблі-краплі. Загін «Тиск» зачищає квартали й збирає трофеї — з них інженери бази роблять нову зброю й броню.' },
  { from: 5, title: 'Бос · Польовий Тиран', text: 'Польовий командир прибульців особисто веде висадку. Без нього їхні загони втратять зв’язок.' },
  { from: 6, title: 'Розділ 2 · Контрнаступ', text: 'Прибульці будують маяки й бункери, щоб викликати основний флот. Ламаємо їхню мережу, поки не пізно.' },
  { from: 10, title: 'Бос · Тиран-вартовий', text: 'Вартовий вулика охороняє шлях до матірного корабля. Його свита — найкращі бійці прибульців.' },
  { from: 11, title: 'Розділ 3 · Серце вулика', text: 'Розвідка знайшла матірний корабель. Кожна місія наближає загін до нього — і кожна втрата важить більше.' },
  { from: FINAL_MISSION, title: 'Фінал · Королева-Тиран', text: 'Королева-Тиран у серці корабля. Убий її — і вторгнення скінчиться.' },
];

export function actOf(missionNo: number) {
  let a = ACTS[0];
  for (const x of ACTS) if (missionNo >= x.from) a = x;
  return missionNo > FINAL_MISSION ? { title: 'Після перемоги · Зачистка', text: 'Вторгнення відбито, але уламки флоту ще розкидані по землі. Безкінечна кампанія: місії стають складнішими.' } : a;
}

export const VICTORY_TEXT = 'Королева-Тиран загинула, і вулик згас. Прибульці без зв’язку розбігаються — вторгнення зупинено. Загін «Тиск» повертається на базу героями.';
